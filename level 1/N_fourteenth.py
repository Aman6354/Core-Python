"""Write a Python program that:

Asks the user to enter the radius of a circle using float.
Use the value:
pi = 3.14
Calculate:
area = pi * radius ** 2
circumference = 2 * pi * radius
Print:
Radius
Area
Circumference"""

radius = float(input("Enter the radius of the circle"))

area = 3.14 * radius ** 2                
circumference = 2 * 3.14 * radius                                                 

print("Area: ", area)
print("Radius: ", radius)
print("Circumference: ", circumference)